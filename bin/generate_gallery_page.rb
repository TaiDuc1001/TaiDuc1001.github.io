#!/usr/bin/env ruby

require 'yaml'

gallery_dir = ARGV[0] || '_pages/gallery'
output_file = ARGV[1] || '_pages/gallery.md'

unless Dir.exist?(gallery_dir)
  warn "Gallery directory not found: #{gallery_dir}"
  exit 1
end

def parse_front_matter(path)
  content = File.read(path)
  match = content.match(/\A---\s*\n(.*?)\n---\s*\n/m)
  return {} unless match

  YAML.safe_load(match[1], permitted_classes: [], aliases: true) || {}
rescue Psych::SyntaxError => e
  warn "Invalid YAML front matter in #{path}: #{e.message}"
  {}
end

def yaml_quote(value)
  "'" + value.to_s.gsub("'", "''") + "'"
end

def split_order_and_slug(basename)
  match = basename.match(/\A(\d+)[-_](.+)\z/)
  return [match[1].to_i, match[2]] if match

  [nil, basename]
end

entries = Dir.glob(File.join(gallery_dir, '*.md')).filter_map do |path|
  fm = parse_front_matter(path)
  next if fm['published'] == false

  basename = File.basename(path, '.md')
  order, slug = split_order_and_slug(basename)

  title = fm['title']&.to_s&.strip
  permalink = fm['permalink']&.to_s&.strip

  title = slug.gsub(/[-_]/, ' ').split.map(&:capitalize).join(' ') if title.nil? || title.empty?
  permalink = "/gallery/#{slug}/" if permalink.nil? || permalink.empty?

  {
    title: title,
    permalink: permalink,
    order: order,
    path: path
  }
end

entries.sort_by! do |entry|
  [
    entry[:order].nil? ? 1 : 0,
    entry[:order].nil? ? 0 : -entry[:order],
    entry[:title].downcase
  ]
end

children_block = if entries.empty?
  "  # No gallery venue pages found in #{gallery_dir}"
else
  entries.map do |entry|
    [
      "  - title: #{yaml_quote(entry[:title])}",
      "    permalink: #{entry[:permalink]}"
    ].join("\n")
  end.join("\n")
end

generated = <<~MARKDOWN
  ---
  layout: page
  title: Gallery
  description: Select a venue from the Gallery dropdown in the navbar.
  nav: true
  nav_order: 6
  dropdown: true
  children:
  #{children_block}
  ---

  <!-- This file is auto-generated by bin/generate_gallery_page.rb from _pages/gallery/*.md -->
  Choose a venue from `Gallery` in the top navigation bar.
MARKDOWN

if File.exist?(output_file) && File.read(output_file) == generated
  puts "No changes detected for #{output_file}; gallery menu is up to date."
  exit 0
end

File.write(output_file, generated)
puts "Generated #{output_file} from #{entries.length} gallery page(s)."
