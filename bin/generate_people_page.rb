#!/usr/bin/env ruby

require 'yaml'

people_dir = ARGV[0] || '_pages/people'
output_file = ARGV[1] || '_pages/people.md'

unless Dir.exist?(people_dir)
  warn "People directory not found: #{people_dir}"
  exit 1
end

def parse_front_matter(path)
  content = File.read(path)
  match = content.match(/\A---\s*\n(.*?)\n---\s*\n/m)
  return {} unless match

  YAML.safe_load(match[1], permitted_classes: [], aliases: true) || {}
rescue Psych::SyntaxError => e
  warn "Invalid YAML front matter in #{path}: #{e.message}"
  {}
end

def yaml_quote(value)
  "'" + value.to_s.gsub("'", "''") + "'"
end

def split_order_and_slug(basename)
  match = basename.match(/\A(\d+)[-_](.+)\z/)
  return [match[1].to_i, match[2]] if match

  [nil, basename]
end

def detect_image_filename(slug)
  %w[png jpg jpeg webp avif gif].each do |ext|
    filename = "#{slug}.#{ext}"
    return filename if File.exist?(File.join('assets/img', filename))
  end
  nil
end

profiles = Dir.glob(File.join(people_dir, '*.md')).filter_map do |path|
  fm = parse_front_matter(path)
  next if fm['published'] == false

  basename = File.basename(path, '.md')
  order, slug = split_order_and_slug(basename)

  {
    order: order,
    basename: basename,
    name: slug,
    image: (fm['image'] || detect_image_filename(slug)),
    image_circular: fm.key?('image_circular') ? fm['image_circular'] : false,
    more_info: fm['more_info'],
    content: File.join('people', "#{basename}.md")
  }
end

profiles.sort_by! do |profile|
  [
    profile[:order].nil? ? 1 : 0,
    profile[:order] || 0,
    profile[:name].downcase
  ]
end

profiles_block = if profiles.empty?
  "[]"
else
  profiles.each_with_index.map do |profile, index|
    align_index = profile[:order] || (index + 1)
    align = align_index.odd? ? 'right' : 'left'

    lines = []
    lines << "  - align: #{align}"
    lines << "    name: #{yaml_quote(profile[:name])}"
    lines << "    image: #{profile[:image]}" if profile[:image]
    lines << "    content: #{profile[:content]}"
    lines << "    image_circular: #{profile[:image_circular] ? 'true' : 'false'}"
    if profile[:more_info].to_s.strip.empty?
      lines << "    more_info: >"
    else
      lines << "    more_info: #{yaml_quote(profile[:more_info])}"
    end
    lines.join("\n")
  end.join("\n")
end

generated = <<~MARKDOWN
  ---
  layout: profiles
  permalink: /people/
  title: People
  description:
  nav: true
  nav_order: 4

  profiles:
  #{profiles_block}
  ---

  <!-- This file is auto-generated by bin/generate_people_page.rb from _pages/people/*.md -->
MARKDOWN

if File.exist?(output_file) && File.read(output_file) == generated
  puts "No changes detected for #{output_file}; people page is up to date."
else
  File.write(output_file, generated)
  puts "Generated #{output_file} from #{profiles.length} people profile(s)."
end
